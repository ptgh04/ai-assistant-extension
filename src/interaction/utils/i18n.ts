export function translate(text: string, language: InterfaceLanguage, values: Record<string, string | number> = {}): string {
  let translated = (language === 'vi' ? vi[text] : en[text]) ?? text;
  if (language === 'vi' && !vi[text]) {
    translated = translated
      .replace(/^Invalid (.+) API key\.$/, 'API key $1 không hợp lệ.')
      .replace(/^The (.+) request timed out\.$/, 'Yêu cầu $1 hết thời gian chờ.')
      .replace(/^(.+): this key cannot access the selected model\.$/, '$1: key này không có quyền truy cập mô hình đã chọn.')
      .replace(/^(.+) rate limit or usage limit reached\. Please try again later\.$/, '$1 đã đạt giới hạn sử dụng. Vui lòng thử lại sau.')
      .replace(/^(.+) is temporarily unavailable\. Please try again\.$/, '$1 tạm thời không khả dụng. Vui lòng thử lại.')
      .replace(/^(.+) returned a streaming error\. Please try again\.$/, '$1 gặp lỗi khi trả lời. Vui lòng thử lại.')
      .replace(/^(.+) request failed with status (\d+)\. Check the model and account access\.$/, '$1 trả về lỗi $2. Kiểm tra mô hình và quyền truy cập tài khoản.');
  }
  for (const [key, value] of Object.entries(values)) translated = translated.replaceAll(`{${key}}`, String(value));
  return translated;
}

export function useI18n() {
  const language = usePreferencesStore((state) => state.language);
  return { language, t: (text: string, values?: Record<string, string | number>) => translate(text, language, values) };
}
